"""Narration: turn an evidence pack into a structured, validated interpretation (LLM when configured, rule-based otherwise)."""

from __future__ import annotations

import json
import logging
import re
import time
from datetime import UTC, datetime
from typing import Any

from app.ai import prompts
from app.ai.evidence import EvidencePack
from app.ai.providers import ProviderError, get_provider
from app.ai.validate import validate

log = logging.getLogger("lotus.ai")


def deterministic_narration(pack: EvidencePack, task: str, question: str | None = None) -> dict[str, Any]:
    """Rule-based narration. Not generated by a model: it restates the computed evidence in order of relevance."""
    use = pack.usable()
    if not use:
        return {
            "summary": "There is not enough computed evidence in this project to answer that yet.",
            "points": [],
            "caveats": [c.text for c in pack.caveats()[:3]],
            "next_steps": [
                "Run an analysis on the relevant variables, or prepare and theme a text column, then ask again."
            ],
        }
    lead = {
        "explain_analysis": "Here is what the computed result says.",
        "answer": "Here is what the computed evidence shows.",
        "insight_narrative": "Supporting evidence for this insight.",
        "mixed_synthesis": "Quantitative and qualitative evidence side by side.",
        "theme_summary": "Computed theme profile.",
        "report_summary": "Key computed findings.",
    }.get(task, "Computed evidence.")
    points = [{"text": f"{i.label}: {i.text}", "evidence": [i.id]} for i in use[:5]]
    return {
        "summary": lead,
        "points": points,
        "caveats": [c.text for c in pack.caveats()[:3]],
        "next_steps": [],
    }


def _extract_json(text: str) -> dict[str, Any]:
    text = text.strip()
    fence = re.search(r"```(?:json)?\s*(\{.*\})\s*```", text, re.S)
    if fence:
        text = fence.group(1)
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1:
        raise ValueError("no JSON object")
    return json.loads(text[start : end + 1])


async def narrate(pack: EvidencePack, task: str, question: str | None = None) -> dict[str, Any]:
    """Returns {narration, meta}. ``meta.origin`` is 'llm' only when a model produced text that passed numeric validation."""
    t0 = time.perf_counter()
    meta: dict[str, Any] = {
        "prompt_version": prompts.PROMPT_VERSION,
        "task": task,
        "generated_at": datetime.now(UTC).isoformat(),
        "origin": "rule",
        "provider": "deterministic",
        "model": None,
        "validation": {"status": "skipped", "problems": []},
        "fallback_reason": None,
    }
    provider = get_provider()
    if provider is not None and pack.usable():
        user = prompts.USER_NARRATOR.format(
            task=prompts.TASKS[task],
            question_line=f"Question: {question}" if question else "",
            evidence=pack.render(),
        )
        try:
            comp = await provider.complete(prompts.SYSTEM_NARRATOR, user)
            raw = _extract_json(comp.text)
            verdict = validate(raw, pack)
            meta.update(
                provider=comp.provider,
                model=comp.model,
                validation={"status": verdict["status"], "problems": verdict["problems"]},
                usage={"input_tokens": comp.input_tokens, "output_tokens": comp.output_tokens},
                evidence_truncated=pack.dropped,
            )
            if verdict["status"] != "failed":
                meta["origin"] = "llm"
                meta["latency_ms"] = int((time.perf_counter() - t0) * 1000)
                return {"narration": verdict["narration"], "meta": meta}
            meta["fallback_reason"] = (
                "The model's text failed numeric validation, so the rule-based summary is shown instead."
            )
        except ProviderError as e:
            meta["fallback_reason"] = (
                f"The AI provider could not be reached ({e}); showing the rule-based summary."
            )
            log.warning("ai_provider_error", extra={"error": str(e)})
        except (ValueError, KeyError, TypeError):
            meta["fallback_reason"] = (
                "The model returned an unreadable answer; showing the rule-based summary."
            )
            log.warning("ai_bad_json")
        meta["provider"], meta["model"] = (
            ("deterministic", None)
            if meta["origin"] == "rule" and meta["validation"]["status"] == "skipped"
            else (meta["provider"], meta["model"])
        )
    meta["latency_ms"] = int((time.perf_counter() - t0) * 1000)
    return {"narration": deterministic_narration(pack, task, question), "meta": meta}
