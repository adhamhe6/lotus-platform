const loginSchema = z.object({ email: z.string().email("Enter a valid e-mail address"), password: z.string().min(1, "Enter your password") });
export function LoginPage() {
  const { login, status } = useAuth();
  const nav = useNavigate();
  const loc = useLocation() as { state?: { from?: string } };
  const [error, setError] = useState<string | null>(null);
  const { register, handleSubmit, formState: { errors, isSubmitting } } = useForm<z.infer<typeof loginSchema>>({ resolver: zodResolver(loginSchema) });
  if (status === "authenticated") return <Navigate to={loc.state?.from ?? "/projects"} replace />;
  return (
    <Shell title="Welcome back" subtitle="Sign in to continue your research." footer={<>New to Lotus? <Link className="font-medium text-primary hover:underline" to="/register">Create an account</Link></>}>
      <form className="space-y-4" noValidate onSubmit={handleSubmit(async (v) => { setError(null); try { await login(v.email, v.password); nav(loc.state?.from ?? "/projects", { replace: true }); } catch (e) { setError(errorMessage(e)); } })}>
        {error && <Alert variant="error">{error}</Alert>}
        <Field label="E-mail" htmlFor="email" error={errors.email?.message}><Input id="email" type="email" autoComplete="email" aria-invalid={!!errors.email} {...register("email")} /></Field>
        <Field label="Password" htmlFor="password" error={errors.password?.message}><Input id="password" type="password" autoComplete="current-password" aria-invalid={!!errors.password} {...register("password")} /></Field>
        <Button type="submit" className="w-full" size="lg" loading={isSubmitting}>Sign in</Button>
      </form>
    </Shell>
  );
}

const registerSchema = z.object({
  full_name: z.string().min(1, "Enter your name").max(200),
  email: z.string().email("Enter a valid e-mail address"),
  password: z.string().min(10, "Use at least 10 characters").refine((p) => /[a-z]/.test(p) && /[A-Z]/.test(p) && /\d/.test(p), "Mix upper- and lower-case letters and include a digit"),
});
export function RegisterPage() {
  const { register: signUp, status } = useAuth();
  const nav = useNavigate();
  const [error, setError] = useState<string | null>(null);
  const { register, handleSubmit, formState: { errors, isSubmitting } } = useForm<z.infer<typeof registerSchema>>({ resolver: zodResolver(registerSchema) });
  if (status === "authenticated") return <Navigate to="/projects" replace />;
  return (
    <Shell title="Create your account" subtitle="Your projects and data stay private to you and the people you invite." footer={<>Already registered? <Link className="font-medium text-primary hover:underline" to="/login">Sign in</Link></>}>
      <form className="space-y-4" noValidate onSubmit={handleSubmit(async (v) => { setError(null); try { await signUp(v.email, v.password, v.full_name); nav("/projects", { replace: true }); } catch (e) { setError(errorMessage(e)); } })}>
        {error && <Alert variant="error">{error}</Alert>}
        <Field label="Full name" htmlFor="full_name" error={errors.full_name?.message}><Input id="full_name" autoComplete="name" aria-invalid={!!errors.full_name} {...register("full_name")} /></Field>
        <Field label="E-mail" htmlFor="email" error={errors.email?.message}><Input id="email" type="email" autoComplete="email" aria-invalid={!!errors.email} {...register("email")} /></Field>
        <Field label="Password" htmlFor="password" hint="At least 10 characters, with upper- and lower-case letters and a digit." error={errors.password?.message}><Input id="password" type="password" autoComplete="new-password" aria-invalid={!!errors.password} {...register("password")} /></Field>
        <Button type="submit" className="w-full" size="lg" loading={isSubmitting}>Create account</Button>
      </form>
    </Shell>
  );
}
