import { BrainCircuit, Calculator, MessagesSquare, ScrollText } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Tooltip } from "@/components/ui/tooltip";

export type ProvenanceKind = "computed" | "qualitative" | "ai" | "rule";

const META = {
  computed: { label: "Computed", variant: "computed", Icon: Calculator, tip: "Calculated by Lotus's statistics engine from your data. Reproducible: same data and configuration give the same number." },
  qualitative: { label: "Qualitative", variant: "qual", Icon: MessagesSquare, tip: "Derived from your text responses: counts come from stored theme/code assignments; quotes are verbatim." },
  ai: { label: "AI interpretation", variant: "ai", Icon: BrainCircuit, tip: "Wording written by a language model from the computed evidence. Numbers in it were validated against that evidence, but the interpretation can still be incomplete." },
  rule: { label: "Rule-based summary", variant: "rule", Icon: ScrollText, tip: "Generated by fixed templates from the computed evidence — no language model was involved." },
} as const;

/** The product-wide distinction between raw data, computed analysis and AI interpretation. */
export function Provenance({ kind, label, className }: { kind: ProvenanceKind; label?: string; className?: string }) {
  const m = META[kind];
  return (
    <Tooltip content={m.tip}>
      <Badge variant={m.variant} className={className}><m.Icon className="size-3" aria-hidden />{label ?? m.label}</Badge>
    </Tooltip>
  );
}

export const interpretationKind = (origin?: string): ProvenanceKind => (origin === "llm" || origin === "ai" ? "ai" : "rule");
